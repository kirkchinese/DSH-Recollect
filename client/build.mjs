// Build lib/client.js (the browser half) from client/page.js and client/locales.mjs.
// No bundler: the output is the same `window.__ModuleLoader__.load` shape DSH's
// own client bundles use, with React and the settings primitives taken from
// the shell's shared module table.
// Usage: node client/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const { ROW_ID, FIELDS } = await import('./fields.mjs');
const { zh, en } = await import('./locales.mjs');
const page = readFileSync(join(root, 'client', 'page.js'), 'utf8');

const out = `// Generated by client/build.mjs — do not edit.
window.__ModuleLoader__.load({
\tid: ${JSON.stringify(pkg.name)},
\tfactory: (require) => {
\t\tvar module = { exports: {} };
\t\tvar exports = module.exports;
\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });
\t\tconst PACKAGE = ${JSON.stringify(pkg.name)};
\t\tconst ROW_ID = ${JSON.stringify(ROW_ID)};
\t\tconst FIELDS = ${JSON.stringify(FIELDS)};
\t\tconst LOCALES = ${JSON.stringify({ zh, en })};
${page}
\t\treturn module.exports;
\t}
});
`;
mkdirSync(join(root, 'lib'), { recursive: true });
writeFileSync(join(root, 'lib', 'client.js'), out);
console.log(`lib/client.js written (${out.length} chars)`);
